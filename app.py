import streamlit as st
import pandas as pd
import plotly.express as px
from ISLP import load_data

# Page configuration
st.set_page_config(
    page_title="Auto Dataset Interactive Dashboard",
    layout="wide"
)

# Load dataset
@st.cache_data
def get_data():
    df = load_data('Auto')
    df['origin_name'] = df['origin'].map({1: 'American', 2: 'European', 3: 'Japanese'})
    return df

auto_df = get_data()

# Dashboard Title
st.title("Auto Dataset Exploratory Analysis Dashboard")
st.markdown("Interactive visualization tool for exploring relationships between vehicle engine parameters, fuel efficiency, and geographical origin.")

# Sidebar Filter
st.sidebar.header("Filter Options")
selected_origin = st.sidebar.selectbox(
    "Select Vehicle Origin:",
    options=['All', 'American', 'European', 'Japanese']
)

# Filter Dataset
if selected_origin != 'All':
    filtered_df = auto_df[auto_df['origin_name'] == selected_origin]
else:
    filtered_df = auto_df

# KPI Summary Cards
col_kpi1, col_kpi2, col_kpi3, col_kpi4 = st.columns(4)
col_kpi1.metric("Total Vehicles", len(filtered_df))
col_kpi2.metric("Mean MPG", f"{filtered_df['mpg'].mean():.2f}")
col_kpi3.metric("Mean Horsepower", f"{filtered_df['horsepower'].mean():.2f} hp")
col_kpi4.metric("Mean Weight", f"{filtered_df['weight'].mean():.2f} lbs")

st.markdown("---")

# Visual Layout: 2x2 Grid
col1, col2 = st.columns(2)

with col1:
    # Visual 1: Scatter Plot (Horsepower vs MPG)
    fig_scatter = px.scatter(
        filtered_df,
        x='horsepower',
        y='mpg',
        color='weight',
        hover_data=['name'] if 'name' in filtered_df.columns else [filtered_df.index],
        title="1. Horsepower vs. MPG (Color = Weight)",
        labels={'horsepower': 'Horsepower (hp)', 'mpg': 'Miles Per Gallon (mpg)'},
        color_continuous_scale='Viridis'
    )
    st.plotly_chart(fig_scatter, use_container_width=True)

with col2:
    # Visual 2: Pie Chart (Origin Distribution)
    origin_counts = filtered_df['origin_name'].value_counts().reset_index()
    origin_counts.columns = ['Origin', 'Count']
    fig_pie = px.pie(
        origin_counts,
        names='Origin',
        values='Count',
        title="2. Vehicle Origin Proportion",
        hole=0.4
    )
    st.plotly_chart(fig_pie, use_container_width=True)

col3, col4 = st.columns(2)

with col3:
    # Visual 3: Histogram (Weight Distribution)
    fig_hist = px.histogram(
        filtered_df,
        x='weight',
        nbins=15,
        title="3. Distribution of Vehicle Weight",
        labels={'weight': 'Weight (lbs)'},
        color_discrete_sequence=['teal']
    )
    st.plotly_chart(fig_hist, use_container_width=True)

with col4:
    # Visual 4: Boxplot (Horsepower Distribution)
    fig_box = px.box(
        filtered_df,
        y='horsepower',
        x='origin_name',
        title="4. Horsepower Spread by Origin",
        labels={'horsepower': 'Horsepower (hp)', 'origin_name': 'Origin'},
        color='origin_name'
    )
    st.plotly_chart(fig_box, use_container_width=True)